func TestInventoryDoesNotFollowSymlinksOutOfTheTree(t *testing.T) {
	// Arrange
	outside, root := t.TempDir(), t.TempDir()
	writeTree(t, outside, map[string]string{
		"requirements.txt": "outside==1.0\n",
		"dir/go.mod":       "module o\nrequire outside.example/a v1.0.0\n",
	})
	writeTree(t, root, map[string]string{"real/requirements.txt": "inside==1.0\n"})
	links := map[string]string{
		filepath.Join(outside, "requirements.txt"):      filepath.Join(root, "requirements.txt"),
		filepath.Join(outside, "dir"):                   filepath.Join(root, "linked"),
		filepath.Join(root, "real", "requirements.txt"): filepath.Join(root, "requirements-inside.txt"),
	}
	for target, link := range links {
		if err := os.Symlink(target, link); err != nil {
			t.Skipf("symbolic links are not available: %v", err)
		}
	}

	// Act
	got, err := Inventory(root)

	// Assert
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"inside@1.0:1"}; !equalStrings(pins(got), want) {
		t.Fatalf("got %v, want %v", pins(got), want)
	}
}

func TestInventorySkipsUnreadableAndOversizedFiles(t *testing.T) {
	// Arrange
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"requirements.txt":     "kept==1.0\n",
		"big/requirements.txt": "big==1.0\n",
		"locked/go.mod":        "module l\nrequire locked.example/a v1.0.0\n",
		"closed/sub/go.mod":    "module c\nrequire closed.example/a v1.0.0\n",
	})
	if err := os.Truncate(filepath.Join(root, "big", "requirements.txt"), maxLockfileBytes+1); err != nil {
		t.Fatal(err)
	}
	// A directory with a lockfile's name is not a lockfile.
	if err := os.MkdirAll(filepath.Join(root, "dirs", "go.mod"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(filepath.Join(root, "locked", "go.mod"), 0); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(filepath.Join(root, "closed"), 0); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.Chmod(filepath.Join(root, "closed"), 0o755) })

	// Act
	got, err := Inventory(root)

	// Assert
	if err != nil {
		t.Fatal(err)
	}
	if os.Getuid() == 0 {
		t.Skip("permission bits do not bind the superuser")
	}
	if want := []string{"kept@1.0:1"}; !equalStrings(pins(got), want) {
		t.Fatalf("got %v, want %v", pins(got), want)
	}
}

func TestInventoryReportsTruncation(t *testing.T) {
	// Arrange
	root := t.TempDir()
	var b strings.Builder
	for i := range maxPackages + 5 {
		fmt.Fprintf(&b, "pkg%d==1.0\n", i)
	}
	writeTree(t, root, map[string]string{"requirements.txt": b.String()})

	// Act
	got, err := Inventory(root)

	// Assert
	if !errors.Is(err, ErrTooManyPackages) {
		t.Fatalf("err = %v, want ErrTooManyPackages", err)
	}
	if len(got) != maxPackages {
		t.Fatalf("got %d packages, want %d", len(got), maxPackages)
	}
}
