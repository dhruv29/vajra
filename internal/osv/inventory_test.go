// pins reduces packages to "name@version:line" for compact comparison.
func pins(pkgs []Package) []string {
	out := make([]string, len(pkgs))
	for i, p := range pkgs {
		out[i] = fmt.Sprintf("%s@%s:%d", p.Name, p.Version, p.Line)
	}
	return out
}

func equalStrings(a, b []string) bool {
	return strings.Join(a, "\x1f") == strings.Join(b, "\x1f") && len(a) == len(b)
}

func TestParsers(t *testing.T) {
	tests := []struct {
		name      string
		parse     lockfileParser
		text      string
		ecosystem string
		want      []string
	}{
		{"go.mod", parseGoMod, goModSample, "Go", []string{
			"golang.org/x/text@v0.3.5:5", "github.com/gorilla/mux@v1.8.0:8",
			"golang.org/x/crypto@v0.0.0-20210921155107-089bfa567519:9", "example.com/quoted@v1.0.0:10",
		}},
		{"go.mod with CRLF", parseGoMod, "module m\r\nrequire a.b/c v1.2.3\r\n", "Go", []string{"a.b/c@v1.2.3:2"}},
		{"go.mod unterminated block", parseGoMod, "require (\n\ta.b/c v1.0.0", "Go", []string{"a.b/c@v1.0.0:2"}},
		{"requirements.txt", parseRequirements, requirementsSample, "PyPI", []string{
			"flask@2.0.1:2", "Django@3.2.4:3", "requests@2.25.1:4", "urllib3@1.26.4:5",
		}},
		{"Cargo.lock", parseCargoLock, cargoLockSample, "crates.io", []string{"serde@1.0.130:12", "time@0.3.1:26"}},
		{"Cargo.lock garbage", parseCargoLock, "[[package]]\nname = \nversion\n[[package", "crates.io", nil},
		{"Gemfile.lock", parseGemfileLock, gemfileLockSample, "RubyGems", []string{
			"actionpack@6.1.3:9", "nokogiri@1.15.4:11", "rack@2.2.3:12",
		}},
		{"Gemfile.lock garbage", parseGemfileLock, "  specs:\n    orphan (1.0)\nGEM\n  specs:\n    x (-)\n     y (1)\n", "RubyGems", nil},
		{"package-lock.json malformed", parsePackageLock, `{"packages": {`, "npm", nil},
		{"package-lock.json wrong shape", parsePackageLock, `{"packages": []}`, "npm", nil},
		{"package-lock.json version 1", parsePackageLock, `{"lockfileVersion":1,"dependencies":{"a":{"version":"1.0.0"}}}`, "npm", nil},
		{"package-lock.json minified", parsePackageLock, `{"packages":{"node_modules/a":{"version":"1.0.0"}}}`, "npm", []string{"a@1.0.0:0"}},
		{"empty", parseGoMod, "", "Go", nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := tt.parse(tt.text)

			if !equalStrings(pins(got), tt.want) {
				t.Fatalf("got %v, want %v", pins(got), tt.want)
			}
			for _, p := range got {
				if p.Ecosystem != tt.ecosystem {
					t.Errorf("%s: ecosystem %q, want %q", p.Name, p.Ecosystem, tt.ecosystem)
				}
			}
		})
	}
}

func TestParsePackageLock(t *testing.T) {
	got := sortedUnique(parsePackageLock(packageLockSample))

	want := []string{"@scope/pkg@2.0.0:13", "b@0.1.0:17", "lodash@4.17.20:9", "real-name@3.0.0:20"}
	if !equalStrings(pins(got), want) {
		t.Fatalf("got %v, want %v", pins(got), want)
	}
	// The version line is shown only when it directly follows the key.
	wantCode := map[string]string{
		"lodash":     ">     9 |     \"node_modules/lodash\": {\n>    10 |       \"version\": \"4.17.20\",\n",
		"@scope/pkg": ">    13 |     \"node_modules/@scope/pkg\": {\n",
	}
	for _, p := range got {
		if code, ok := wantCode[p.Name]; ok && p.code != code {
			t.Errorf("%s: code %q, want %q", p.Name, p.code, code)
		}
	}
}

func TestParsersCaptureThePinningLines(t *testing.T) {
	tests := []struct {
		name string
		got  []Package
		want string
	}{
		{"go.mod", parseGoMod("module m\nrequire a.b/c v1.2.3 // indirect\n"), ">     2 | require a.b/c v1.2.3 // indirect\n"},
		{"requirements", parseRequirements("flask==2.0.1\n"), ">     1 | flask==2.0.1\n"},
		{"cargo", parseCargoLock("[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nsource = \"registry\"\n"),
			">     2 | name = \"a\"\n>     3 | version = \"1.0.0\"\n"},
		{"gems", parseGemfileLock("GEM\n  specs:\n    rack (2.2.3)\n"), ">     3 |     rack (2.2.3)\n"},
		{"long line", parseRequirements("flask==2.0.1 #" + strings.Repeat("x", 400) + "\n"),
			">     1 | " + ("flask==2.0.1 #" + strings.Repeat("x", 400))[:maxLineChars] + " [line truncated]\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if len(tt.got) != 1 {
				t.Fatalf("got %d packages, want 1", len(tt.got))
			}
			if tt.got[0].code != tt.want {
				t.Errorf("code %q, want %q", tt.got[0].code, tt.want)
			}
		})
	}
}

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestInventoryReadsEveryFormatSortedAndDeduplicated(t *testing.T) {
	// Arrange
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":                    "module m\nrequire b.example/z v1.0.0\nrequire a.example/y v2.0.0\n",
		"web/package-lock.json":     packageLockSample,
		"svc/requirements.txt":      "flask==2.0.1\n",
		"svc/requirements-dev.txt":  "flask==2.0.1\npytest==6.2.4\n",
		"svc/notrequirements.txt":   "ignored==1.0\n",
		"rs/Cargo.lock":             cargoLockSample,
		"rb/Gemfile.lock":           gemfileLockSample,
		"other/go.mod":              "module n\nrequire a.example/y v2.0.0\nrequire a.example/y v1.9.0\n",
		"README.md":                 "flask==9.9.9\n",
		"node_modules/x/go.mod":     "module x\nrequire skipped.example/a v1.0.0\n",
		"vendor/y/requirements.txt": "skipped==1.0\n",
		".git/go.mod":               "module g\nrequire skipped.example/b v1.0.0\n",
		"web/dist/Cargo.lock":       cargoLockSample + "\n[[package]]\nname = \"skipped\"\nversion = \"1.0.0\"\nsource = \"r\"\n",
		"a/build/go.mod":            "module g\nrequire skipped.example/c v1.0.0\n",
		".venv/requirements.txt":    "skipped==2.0\n",
		"rs/target/Gemfile.lock":    "GEM\n  specs:\n    skipped (1.0)\n",
	})

	// Act
	got, err := Inventory(root)

	// Assert
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"Go a.example/y@v1.9.0 other/go.mod:3",
		"Go a.example/y@v2.0.0 go.mod:3",
		"Go b.example/z@v1.0.0 go.mod:2",
		"PyPI flask@2.0.1 svc/requirements-dev.txt:1",
		"PyPI pytest@6.2.4 svc/requirements-dev.txt:2",
		"RubyGems actionpack@6.1.3 rb/Gemfile.lock:9",
		"RubyGems nokogiri@1.15.4 rb/Gemfile.lock:11",
		"RubyGems rack@2.2.3 rb/Gemfile.lock:12",
		"crates.io serde@1.0.130 rs/Cargo.lock:12",
		"crates.io time@0.3.1 rs/Cargo.lock:26",
		"npm @scope/pkg@2.0.0 web/package-lock.json:13",
		"npm b@0.1.0 web/package-lock.json:17",
		"npm lodash@4.17.20 web/package-lock.json:9",
		"npm real-name@3.0.0 web/package-lock.json:20",
	}
	var lines []string
	for _, p := range got {
		lines = append(lines, fmt.Sprintf("%s %s@%s %s:%d", p.Ecosystem, p.Name, p.Version, p.File, p.Line))
	}
	if !equalStrings(lines, want) {
		t.Fatalf("got:\n%s\nwant:\n%s", strings.Join(lines, "\n"), strings.Join(want, "\n"))
	}
}

